#pragma once
#include <cstdint>
#include <vector>

namespace acoustic_radar {

// Результат сопоставления входа с известным синхросигналом OUTPUT 1 → INPUT 1.
// sampleIndex указывает начало эталона в переданном буфере, в аудиокадрах,
// а не в отдельных float-элементах и не в байтах. При 48 кГц индекс 48000
// соответствует одной секунде от начала буфера. Абсолютную позицию потока
// вычисляет вызывающая сторона, добавляя смещение начала своего буфера.
//
// correlation — нормированная оценка сходства формы сигнала, не громкость,
// не вероятность обнаружения и не измеренная акустическая задержка.
// Для конечных ненулевых сигналов теоретический диапазон [-1, 1]:
// +1 — точное совпадение с положительным масштабом амплитуды;
//  0 — нулевое скалярное произведение с эталоном;
// -1 — совпадение с инверсией полярности, которое этот детектор не принимает.
struct SyncMarker
{
    uint64_t sampleIndex;
    double correlation;
};

// Пакетный детектор положительно коррелированных маркеров: для каждого
// возможного положения сопоставляет отрезок INPUT 1 с известным эталоном.
// Поиск не зависит от времени отправки OUTPUT 1 или момента вызова callback,
// поэтому учитывает фактическое положение маркера в принятом аудиосигнале.
//
// Объект не хранит историю между detect(): каждый вызов начинает поиск заново.
// Накопление данных, ожидание полного цикла, повторный поиск после тишины
// и разрывов обеспечивает CycleProcessor. Детектор не выполняет FFT микрофона
// и не выделяет акустические резонансы — это задача SpectrumAnalyzer.
class SyncDetector final
{
public:
    // input — четырёхканальный Float32 с чередованием отсчётов; читается канал 0:
    // input[0], input[4], input[8], ... . frames — число аудиокадров, не float.
    // Вызывающая сторона обеспечивает frames*4 доступных элементов и неизменность
    // буфера до возврата; данные не сохраняются внутри детектора.
    //
    // Начальное совпадение выбирается в пределах первого периода, последующие
    // ищутся через период с допуском ±512 кадров. Вернутся только пики выше
    // порога; отсутствие промежуточного маркера не завершает поиск остальных.
    // Пустой результат означает, что начальный маркер не найден, вход nullptr
    // или данных меньше длительности эталона. В этом вызове поиск за первым
    // периодом не выполняется, пока в нём не найдено начальное совпадение.
    //
    // Поиск требует заметного времени и выделяет память под эталон и результаты:
    // вызывать в рабочем потоке, не в обработчике PortAudio.
    [[nodiscard]] std::vector<SyncMarker> detect(
        const float* input,
        size_t frames
    ) const;
};

} // пространство имён acoustic_radar
