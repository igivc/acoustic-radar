/**
 * @file ring.hpp
 * @brief Кольцевая очередь с одним потоком записи и одним потоком чтения.
 */
#pragma once
#include <array>
#include <atomic>
#include <cstddef>
#include <cstdint>

namespace acoustic_radar {
/**
 * @brief Кольцевая очередь для одного потока записи и одного потока чтения.
 *
 * SPSC (Single Producer, Single Consumer) - очередь ровно с одним потоком записи и одним потоком чтения.
 *
 * В проекте push() вызывает callback PortAudio,
 * а pop() - ProcessingWorker. Два одновременных вызова push() из разных потоков
 * или два pop() не поддерживаются: у очереди должен быть только один писатель и один читатель.
 *
 * Данные расположены в заранее выделенном массиве. Индексы read_ и write_
 * обозначают число прочитанных и записанных элементов, а остаток от деления
 * на Capacity выбирает физическую ячейку. Например, при Capacity=4 индексы
 * 0, 4, 8 используют одну ячейку; читать её можно только после завершения записи,
 * а записывать повторно - только после завершения предыдущего чтения.
 *
 * Число элементов = write_ - read_: 0 означает пустую очередь, Capacity - полную.
 * Используются все Capacity ячеек, запасная пустая ячейка не требуется.
 * Заполненная очередь не принимает новые данные; непрочитанные не перезаписываются.
 * Методы не ждут свободного места или данных и не используют мьютекс.
 *
 * Ограничения шаблона: Capacity должна быть положительной, тип T - допускать
 * создание по умолчанию и присваивание копированием. Для применения в звуковом
 * обработчике копирование T должно быть быстрым, без выделений и исключений:
 * методы noexcept, поэтому исключение из присваивания завершит процесс.
 * В проекте T=InputFrame - небольшая структура с числами и массивом отсчётов.
 * Уничтожать очередь можно только после завершения обращений обоих потоков.
 *
 * Шаблон реализован целиком здесь: компилятору нужны определения методов
 * при создании конкретного SpscRing<T, Capacity>, поэтому отдельного ring.cpp нет.
 *
 * @tparam T Тип передаваемого элемента с копирующим присваиванием без исключений.
 * @tparam Capacity Положительное число ячеек очереди.
 */
template<class T, size_t Capacity> class SpscRing final {
public:
    /**
     * @brief Копирует один элемент и возвращает true после завершения записи.
     *
     * При false очередь не меняется: вызывающий поток сам решает, отбросить
     * данные или повторить попытку. Callback PortAudio отбрасывает кадр,
     * увеличивает счётчик потерь и продолжает выдачу звука без ожидания.
     *
     * @param value Элемент для записи в следующую свободную ячейку.
     * @return true при успешной записи; false при заполненной очереди.
     * @note Вызывать только из потока записи.
     */
    bool push(const T& value) noexcept {
        // write_ изменяет только поток записи. При чтении своего индекса ему
        // не нужно синхронизироваться с другим потоком, поэтому достаточно relaxed.
        const auto write = write_.load(std::memory_order_relaxed);
        // Поток чтения увеличивает read_ после копирования элемента.
        // Если новое значение ещё не видно, push может вернуть false.
        // Поток записи сможет повторить попытку при следующем обращении.
        if (write - read_.load(std::memory_order_acquire) == Capacity) return false;
        // Прочитав новое read_ с acquire, знаем, что потребитель уже закончил
        // копировать данные из ячейки. Теперь её можно заполнить заново.
        data_[write % Capacity] = value;
        // Сначала записываем элемент, затем увеличиваем write_ с release.
        // Когда pop прочитает новый write_ с acquire, ему будет видно и значение T.
        // Поэтому поля T не обязаны быть атомарными.
        write_.store(write + 1, std::memory_order_release);
        return true;
    }
    /**
     * @brief Копирует самый старый записанный элемент в value и освобождает ячейку.
     *
     * При пустой очереди возвращает false, не меняя value. Потребитель может
     * повторить чтение позже; внутри метода ожидания появления данных нет.
     *
     * @param[out] value Прочитанный элемент; при пустой очереди не меняется.
     * @return true при успешном чтении; false при пустой очереди.
     * @note Вызывать только из потока чтения.
     */
    bool pop(T& value) noexcept {
        // read_ изменяет только поток чтения: достаточно relaxed.
        // write_ читаем с acquire, чтобы увидеть данные, записанные другим потоком.
        const auto read = read_.load(std::memory_order_relaxed);
        if (read == write_.load(std::memory_order_acquire)) return false;
        // Увеличенный write_ означает, что элемент полностью записан.
        // Копируем его, прежде чем разрешить производителю занять ячейку снова.
        value = data_[read % Capacity];
        // Освобождаем ячейку после копирования: производитель не может изменить
        // её содержимое, пока потребитель ещё переносит его в value.
        read_.store(read + 1, std::memory_order_release);
        return true;
    }
private:
    // Если атомик на платформе реализован через скрытую блокировку, очередь
    // не подходит для callback; такую сборку отклоняем на этапе компиляции.
    static_assert(std::atomic<uint64_t>::is_always_lock_free);
    /**
     * @brief Во время push/pop массив не расширяется; память является частью объекта.
     *
     * Большое кольцо AudioDevice размещает в динамической памяти до старта звука.
     */
    std::array<T, Capacity> data_{};
    /**
     * @brief Выравнивание на 64 байта разносит индексы чтения и записи по разным строкам кэша, чтобы их
     * обновление разными потоками реже вызывало лишний обмен данными между ядрами процессора.
     *
     * Выравнивание ускоряет обмен на типичных процессорах; правильность передачи
     * обеспечивают атомарные операции, а не расположение индексов в памяти.
     * При переполнении uint64_t счётчик переходит от максимума к нулю.
     * В рабочем кольце Capacity=131072 делит 2^64 без остатка, поэтому этот
     * переход сохраняет порядок ячеек. Для других ёмкостей это не гарантируется.
     * Обычный переход от конца массива к началу выполняется через % Capacity.
     */
    alignas(64) std::atomic<uint64_t> write_{0};
    alignas(64) std::atomic<uint64_t> read_{0};
};
/**
 * @brief Один входной аудиокадр содержит четыре одновременных отсчёта - по одному на каждый канал PortAudio.
 *
 * Это не блок из четырёх последовательных моментов.
 * samples[0] используется для синхромаркера, samples[1] - для микрофона.
 *
 * index - абсолютная позиция в исходном аудиопотоке, независимая от read_/write_.
 * При отказе push() индекс аудиопотока продолжает расти, а write_ не меняется.
 * Поэтому индекс следующего принятого InputFrame позволяет заметить пропуск: обработчик сбрасывает
 * неполный цикл и не вычисляет FFT по склеенным несмежным участкам звука.
 */
struct InputFrame {
    /**
     * @brief Абсолютный индекс кадра в исходном аудиопотоке.
     */
    uint64_t index;
    /**
     * @brief Одновременные отсчёты четырёх входов; индексы 0 и 1 задают INPUT 1 и INPUT 2.
     */
    std::array<float, 4> samples;
};
}
