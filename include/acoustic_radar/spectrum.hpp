#pragma once
#include <array>
#include <cstddef>
#include <cstdint>
#include <vector>
#include <fftw3.h>

namespace acoustic_radar {
// STFT (Short-Time Fourier Transform) — кратковременное преобразование Фурье:
// делим сигнал на короткие перекрывающиеся участки (окна) и считаем FFT каждого.
// Каждый спектр показывает, какие частоты присутствовали в своём интервале времени;
// последовательность спектров образует столбцы спектрограммы.
//
// При частоте дискретизации 48000 Гц:
//   размер окна 4096 отсчётов → длительность измерения 85,33 мс;
//   шаг 1024 отсчёта → новый столбец каждые 21,33 мс;
//   соседние окна имеют 3072 общих отсчёта, то есть перекрываются на 75%;
//   частотный шаг FFT равен 48000 / 4096 = 11,71875 Гц.
// Увеличение окна уменьшает частотный шаг, но объединяет более длинный участок
// сигнала в одно измерение. Быстрые изменения становятся менее заметны.
// Перекрытие даёт более частые измерения, не сокращая длительность самого окна.
inline constexpr size_t SpectrumFFTSize = 4096;
inline constexpr size_t SpectrumHopSize = SpectrumFFTSize / 4;
// Один столбец STFT — результат анализа одного окна, а не одного отсчёта.
// timeSeconds — время середины окна относительно начала синхромаркера.
// decibels[b] — амплитудный уровень частотного бина b в dBFS.
// Бин — элемент дискретной частотной сетки: f(b) = b * SampleRate / FFTSize.
// Для вещественного входа храним FFTSize / 2 + 1 значений: от постоянной
// составляющей (b=0) до частоты Найквиста (b=2048, f=24000 Гц).
// Для вещественного сигнала отрицательные частоты не дают новой информации:
// их комплексные коэффициенты сопряжены с коэффициентами положительных частот.
// Массив содержит весь этот диапазон; отображаемую полосу выбирает визуализация.
struct SpectrumColumn {
    double timeSeconds;
    std::array<float, SpectrumFFTSize / 2 + 1> decibels;
};
// Спектральный кадр — набор столбцов для одного полного цикла возбуждения.
// Здесь «кадр» не означает аудиокадр PortAudio: тот содержит четыре отсчёта,
// а SpectrumFrame содержит результат анализа целого секундного интервала.
// Результат готов к передаче в интерфейс; исходный аудиобуфер ему больше не нужен.
struct SpectrumFrame {
    // В результате analyze() это исходный индекс маркера в переданном буфере.
    // CycleProcessor добавляет base_, преобразуя его в абсолютный индекс потока.
    uint64_t markerSample;
    // Качество корреляционного обнаружения; анализатор не вычисляет его заново
    // и не использует для изменения амплитуд или отбора спектральных столбцов.
    double correlation;
    // Столбцы упорядочены по времени; каждый содержит полный спектр окна,
    // а не только максимум или заранее выбранные резонансные частоты.
    std::vector<SpectrumColumn> columns;
};
// Создаёт и освобождает FFTW-план, хранит его рабочие массивы. Не потокобезопасен:
// каждый вычисляющий поток создаёт собственный экземпляр.
// Создание плана и выделение памяти под результаты выполняются вне звукового
// callback. Последующие analyze() повторно используют рабочие массивы и план,
// но возвращают новый независимый набор спектров. Запрет копирования предотвращает
// копирование указателя на план: иначе два объекта попытались бы освободить его.
class SpectrumAnalyzer final {
public:
    static constexpr size_t FFTSize = SpectrumFFTSize;
    static constexpr size_t HopSize = SpectrumHopSize;
    SpectrumAnalyzer();
    ~SpectrumAnalyzer();
    SpectrumAnalyzer(const SpectrumAnalyzer&) = delete;
    SpectrumAnalyzer& operator=(const SpectrumAnalyzer&) = delete;
    // interleaved содержит frames кадров по четыре Float32-отсчёта каждый.
    // markerSample — индекс кадра начала маркера в переданном буфере, не номер
    // отдельного float. Анализируется канал с индексом 1 на протяжении цикла.
    // correlation переносится в результат как оценка качества синхронизации.
    // При недостатке данных возвращается результат без столбцов. Исходный
    // буфер не сохраняется: результат содержит свои массивы рассчитанных уровней.
    // При ненулевом указателе вызывающая сторона должна предоставить как минимум
    // frames * 4 доступных элементов и не менять их во время analyze(). Размер
    // выделенной памяти по одному указателю определить невозможно.
    // Один вызов не ищет маркер и не ждёт поступления данных — он анализирует
    // уже найденный цикл; накоплением и синхронизацией занимается CycleProcessor.
    SpectrumFrame analyze(const float* interleaved, size_t frames,
                          uint64_t markerSample, double correlation);
private:
    // Отсчёты одного окна, умноженные на коэффициенты Ханна. Float32 преобразуется в double
    // при умножении на коэффициент окна для double-версии FFTW.
    std::array<double, FFTSize> input_{};
    // Коэффициенты Ханна вычисляются один раз, не заново для каждого столбца.
    std::array<double, FFTSize> window_{};
    // Комплексный бин FFTW хранит действительную и мнимую части в [b][0/1].
    fftw_complex output_[FFTSize / 2 + 1]{};
    // План описывает вычисление с конкретными адресами input_ и output_.
    fftw_plan plan_ = nullptr;
    // Сумма коэффициентов окна для восстановления масштаба пиковых амплитуд.
    double windowSum_ = 0;
};
}
