#pragma once
#include "acoustic_radar/audio.hpp"
#include "acoustic_radar/sync.hpp"
#include "acoustic_radar/spectrum.hpp"
#include <deque>
#include <mutex>
#include <thread>
#include <exception>
#include <optional>
namespace acoustic_radar {
/**
 * @brief Преобразует непрерывную последовательность входных аудиокадров в завершённые спектры полных циклов.
 *
 * Границы блоков PortAudio не совпадают с границами циклов:
 * начало определяется только корреляцией синхромаркера во входном канале 0.
 *
 * Состояния сборщика:
 *   1. Накопление данных и поиск синхромаркера.
 *   2. Ожидание полного цикла после найденного маркера.
 *   3. Анализ микрофона, выдача спектра и удаление обработанного начала буфера.
 * При разрыве абсолютных индексов возвращается в состояние накопления.
 * Хранит только необходимый хвост; длительность сессии не увеличивает буфер.
 * append() вызывается последовательно одним рабочим потоком; мьютекса внутри нет.
 */
class CycleProcessor {
public:
    /**
     * @brief Добавляет один кадр (четыре одновременных входных отсчёта), не блок звука.
     *
     * Обычно результат пуст: пока не найден маркер и не получен весь цикл,
     * FFT не выполняется. Каждый возвращаемый спектр содержит свои данные
     * и не ссылается на внутренний буфер. Его можно передать в очередь.
     *
     * @param frame Следующий входной кадр с абсолютным индексом.
     * @return Готовые спектральные кадры либо пустой вектор, пока полный цикл не накоплен.
     * @note При разрыве индексов сбрасывает неполный цикл.
     */
    std::vector<SpectrumFrame> append(const InputFrame& frame);
private:
    SpectrumAnalyzer analyzer_;
    /**
     * @brief Чередующиеся отсчёты четырёх каналов: размер измеряется числом элементов float, а не
     * аудиокадров.
     *
     * Кадр с локальным индексом k расположен начиная с samples_[k * 4].
     */
    std::vector<float> samples_;
    /**
     * @brief Абсолютный индекс первого кадра в samples_; растёт при удалении начала буфера.
     */
    uint64_t base_ = 0;
    /**
     * @brief Ожидаемый индекс следующего кадра для обнаружения потерь в кольце.
     */
    uint64_t nextIndex_ = 0;
    bool initialized_ = false;
    /**
     * @brief Позиция найденного маркера относительно начала samples_.
     *
     * Пока ждём
     * остаток цикла, начало буфера не удаляется и эта позиция остаётся действительной.
     */
    std::optional<SyncMarker> pendingMarker_;
};
/**
 * @brief Соединяет входное кольцо, обработку циклов и очередь готовых спектров.
 *
 * Соединяет два независимых канала передачи:   PortAudio -> SPSC-кольцо -> рабочий поток: исходные аудиокадры;   рабочий поток -> очередь ready_ -> основной поток SDL: готовые спектры.
 *
 * FFT и корреляция выполняются только в рабочем потоке, SDL - только в основном.
 * Мьютекс защищает очередь результатов и запись об ошибке; обработчик PortAudio
 * никогда его не захватывает и не ждёт отображения.
 * AudioDevice передаётся по ссылке и должен существовать до завершения worker.
 */
class ProcessingWorker final {
public:
    /**
     * @brief Немедленно запускает поток; обычно создаётся перед audio.start().
     *
     * @param audio Устройство, из которого читается входное кольцо.
     * @pre Устройство существует до завершения рабочего потока.
     */
    explicit ProcessingWorker(AudioDevice& audio);
    /**
     * @brief Запрашивает остановку и ждёт завершения.
     *
     * Оставшиеся аудиоданные и незавершённый
     * цикл при этом могут остаться необработанными: остановка не требует завершить всю накопленную работу.
     */
    ~ProcessingWorker();
    /**
     * @brief Вызывается из основного потока: забирает все накопленные результаты в порядке поступления и
     * освобождает очередь.
     *
     * Если вычислительный поток
     * завершился с исключением, повторно выбрасывает его в вызывающем потоке.
     *
     * @return Все накопленные результаты в порядке поступления.
     * @note Ошибка рабочего потока повторно выбрасывается в вызывающем потоке.
     */
    std::vector<SpectrumFrame> take();
    /**
     * @brief Число удалённых готовых циклов; не путать с потерей входных аудиокадров.
     *
     * @return Число удалённых старых результатов из очереди ready_.
     */
    uint64_t droppedResults() const noexcept { return droppedResults_.load(); }
private:
    std::mutex mutex_;
    /**
     * @brief Храним не более восьми результатов.
     *
     * Перед добавлением девятого удаляем старый.
     */
    std::deque<SpectrumFrame> ready_;
    std::exception_ptr error_;
    std::atomic<uint64_t> droppedResults_{0};
    /**
     * @brief Объявлен последним: все поля, доступные запускаемой функции, уже созданы к моменту запуска.
     *
     * Деструктор явно ждёт поток до разрушения этих полей.
     */
    std::jthread thread_;
};
}
