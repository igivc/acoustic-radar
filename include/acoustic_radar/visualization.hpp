/**
 * @file visualization.hpp
 * @brief Накопление и отображение спектрограммы средствами SDL3.
 */
#pragma once
#include "acoustic_radar/spectrum.hpp"
#include <SDL3/SDL.h>
namespace acoustic_radar {
/**
 * @brief Показывает спектры последовательных циклов и сохраняет историю.
 *
 * Здесь нет FFT
 * и поиска синхромаркеров: класс получает готовые SpectrumFrame от обработчика.
 * X - время центра окна FFT от маркера, Y - частота, оттенок - также частота,
 * непрозрачность новой ячейки зависит от амплитудного уровня соответствующего бина.
 *
 * История изменяется только при add() или смене диапазона. draw() можно вызывать
 * чаще прихода спектров: он выводит текущее изображение, не ускоряя затухание.
 * Это разделяет частоту обновления окна и частоту измерительных циклов.
 *
 * Все методы, включая создание и уничтожение, вызывать только из SDL-потока.
 * SDL_Renderer создаёт и удаляет main, причём удаляет после Spectrogram.
 * Сам Spectrogram создаёт текстуру истории и удаляет её в своём деструкторе.
 */
class Spectrogram final {
public:
    /**
     * @brief Создаёт текстуру для отрисовки в неё; renderer должен поддерживать SDL_TEXTUREACCESS_TARGET.
     *
     * Ошибки создания передаются исключением.
     *
     * @param renderer Внешний renderer с поддержкой SDL_TEXTUREACCESS_TARGET.
     * @pre renderer существует до уничтожения Spectrogram.
     * @throws std::runtime_error Ошибка создания или настройки SDL-текстуры.
     */
    explicit Spectrogram(SDL_Renderer* renderer);
    /**
     * @brief Удаляет текстуру накопления, сохраняя внешний renderer.
     */
    ~Spectrogram();
    Spectrogram(const Spectrogram&) = delete;
    Spectrogram& operator=(const Spectrogram&) = delete;
    /**
     * @brief Задаёт нижнюю границу оси Y; верхняя всегда lowHz+1000 Гц.
     *
     * При изменении очищает историю, при повторе прежнего значения ничего не делает.
     * Допустимый диапазон ограничивает управляющий код, не этот метод.
     *
     * @param lowHz Нижняя частота отображаемой полосы в герцах.
     */
    void setRange(int lowHz);
    /**
     * @brief Один непустой кадр соответствует одному шагу накопления: затемнение истории на 40%, затем
     * нанесение его ячеек.
     *
     * Не хранит ссылку на frame.
     * Пустой кадр не меняет ни изображение, ни счётчик циклов.
     *
     * @param frame Готовые спектры одного цикла; пустой кадр игнорируется.
     */
    void add(const SpectrumFrame& frame);
    /**
     * @brief Рисует историю, оси и служебные подписи в текущий размер окна и вызывает SDL_RenderPresent.
     *
     * durationMs задаёт лишь положение вертикальной линии
     * конца возбуждения; он не меняет данные спектра или генератор звука.
     * Поверх истории выводит сетку с шагом 100 мс и 200 Гц.
     *
     * @param durationMs Длительность возбуждения в миллисекундах для отметки на графике.
     */
    void draw(int durationMs);
private:
    /**
     * @brief Указатель на renderer, созданный в main.
     *
     * Этот класс его не удаляет.
     */
    SDL_Renderer* renderer_;
    /**
     * @brief Собственная текстура фиксированного размера с накопленной историей.
     */
    SDL_Texture* accumulation_ = nullptr;
    int lowHz_ = 1900;
    /**
     * @brief Число нанесённых кадров с момента очистки, не общее число аудиоциклов.
     */
    unsigned cycles_ = 0;
    /**
     * @brief Корреляция последнего нанесённого кадра для подписи качества синхронизации.
     */
    double correlation_ = 0;
    /**
     * @brief Заполняет историю чёрным и сбрасывает cycles_.
     *
     * correlation_ не сбрасывает.
     */
    void clear();
};
}
