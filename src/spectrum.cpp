#include "acoustic_radar/spectrum.hpp"
#include "acoustic_radar/chirp.hpp"
#include <algorithm>
#include <cmath>
#include <stdexcept>

namespace acoustic_radar {
SpectrumAnalyzer::SpectrumAnalyzer() {
    // FFT рассматривает конечный фрагмент как периодически повторяющийся.
    // Если конец фрагмента не стыкуется с началом, при повторении возникает скачок.
    // В спектре появляются лишние составляющие — спектральная утечка.
    // Окно Ханна плавно уменьшает амплитуду у краёв. Благодаря этому уменьшаются
    // боковые лепестки — слабые пики по сторонам от основного спектрального пика.
    // При этом основной пик становится шире: шаг бинов не означает, что два
    // произвольных тона на расстоянии одного шага обязательно будут различимы.
    // Для восстановления амплитуды делим результат на сумму коэффициентов окна.
    // Для оценки мощности применялась бы другая нормировка — с суммой квадратов.
    for (size_t i = 0; i < FFTSize; ++i) {
        window_[i] = .5 - .5 * std::cos(2 * std::acos(-1.) * i / (FFTSize - 1));
        windowSum_ += window_[i];
    }
    // План привязан к адресам input_/output_ и повторно используется для всех окон.
    // Один экземпляр анализатора обслуживается одним потоком.
    // Преобразование r2c означает «вещественные отсчёты → комплексный спектр».
    // FFTW_ESTIMATE выбирает план без длительного подбора по пробным замерам;
    // создание плана не является частью обработки каждого окна.
    plan_ = fftw_plan_dft_r2c_1d(FFTSize, input_.data(), output_, FFTW_ESTIMATE);
    if (!plan_) throw std::runtime_error("Cannot create FFTW plan");
}
// План освобождается раньше рабочих массивов, являющихся полями объекта.
// Глобальная очистка FFTW здесь не вызывается: другие анализаторы могут ещё
// владеть своими планами; освобождаем только ресурс этого экземпляра.
SpectrumAnalyzer::~SpectrumAnalyzer() { fftw_destroy_plan(plan_); }
SpectrumFrame SpectrumAnalyzer::analyze(const float* data, size_t frames,
                                        uint64_t marker, double correlation) {
    SpectrumFrame result{marker, correlation, {}};
    // Сначала проверяем marker > frames, и только затем вычисляем frames-marker:
    // Если marker > frames, оператор || не вычисляет следующие условия.
    // Поэтому беззнаковое frames-marker не переполняется из-за такого входа.
    // Если буфер длиннее цикла, хвост после него не анализируется этим вызовом.
    // Неполный цикл не дополняем нулями, чтобы не рисовать искусственный спад.
    if (!data || marker > frames || frames - marker < ChirpGenerator::CycleSamples)
        return result;
    // Проход STFT: offset — начало окна относительно маркера, в аудиокадрах.
    // Окна [0,4096), [1024,5120), [2048,6144), ... перекрываются на 75%.
    // Берём только окна, целиком находящиеся внутри цикла; границы нулями
    // не дополняем и отсчёты следующего цикла в текущий спектр не включаем.
    // Число столбцов при длине цикла L, размере FFT N и шаге H:
    // floor((L-N)/H)+1 при L>=N. Для L=48000, N=4096, H=1024 это 43 столбца:
    // последнее окно содержит отсчёты с индексами от 43008 до 47103 включительно,
    // его центр — 45056/48000 = 938,67 мс. Первые и последние точки оси
    // не имеют столбцов, поскольку для них потребовался бы выход за границы цикла.
    for (size_t offset = 0; offset + FFTSize <= ChirpGenerator::CycleSamples; offset += HopSize) {
        // Четыре входных канала с чередованием отсчётов; микрофон читается из канала с индексом 1.
        // Адрес = (кадр маркера + смещение окна + отсчёт в окне)*4 + канал.
        // Например, для marker=100, offset=0, j=0 берётся data[401],
        // а следующий отсчёт того же микрофона расположен в data[405].
        for (size_t j = 0; j < FFTSize; ++j)
            input_[j] = data[(marker + offset + j) * 4 + 1] * window_[j];
        // Для каждого окна вычисляется отдельная FFT. Результат содержит
        // комплексные коэффициенты: их модуль задаёт амплитуду, аргумент — фазу.
        // Для данной спектрограммы фаза не используется.
        fftw_execute(plan_);
        SpectrumColumn column{};
        // Частота измеряется на всём интервале окна; её нельзя приписать одному
        // отсчёту. По оси X ставим результат в середину измерительного окна.
        // Первый столбец имеет время 2048/48000 = 42,67 мс от маркера,
        // второй — 3072/48000 = 64 мс. Это время сигнала, не время расчёта FFT.
        column.timeSeconds = (offset + FFTSize / 2.) / ChirpGenerator::SampleRate;
        for (size_t b = 0; b <= FFTSize / 2; ++b) {
            // FFTW не нормирует результат: сначала делим модуль коэффициента
            // на сумму окна. У вещественного синуса амплитуда разделена между
            // положительной и отрицательной частотами; для одностороннего спектра
            // удваиваем модуль положительной части. DC и частота Найквиста
            // не имеют отдельной зеркальной пары и не требуют удвоения.
            // Для синуса в центре бина между нулевой частотой и частотой Найквиста получаем примерно исходную
            // пиковую амплитуду, а не среднеквадратичную (RMS).
            // Если частота тона не совпадает с бином, энергия распределяется между бинами,
            // поэтому максимум одного бина может недооценивать амплитуду тона.
            const double scale = (b == 0 || b == FFTSize / 2) ? 1 : 2;
            const double amplitude = scale * std::hypot(output_[b][0], output_[b][1]) / windowSum_;
            // Амплитудный уровень: 20*log10(A), где A=1 соответствует 0 dBFS,
            // A=0,5 — примерно -6,02 dBFS. Это не плотность мощности и не дБ SPL:
            // акустическая калибровка микрофона здесь не выполняется.
            // Для конечного A>=0 предел 1e-10 даёт нижний предел -200 dBFS и исключает
            // log(0). Важно: std::max не заменяет NaN конечным числом; входные NaN пока проходят
            // дальше и требуют отдельной обработки (известное ограничение).
            column.decibels[b] = static_cast<float>(20 * std::log10(std::max(amplitude, 1e-10)));
        }
        // Сохраняем все 2049 бинов. Обрезка до отображаемого диапазона,
        // спектральная палитра и затухание истории относятся к визуализации.
        // Здесь нет поиска одного «главного тона»: несколько резонансов могут
        // присутствовать одновременно и должны оставаться в спектре.
        result.columns.push_back(column);
    }
    return result;
}
}
